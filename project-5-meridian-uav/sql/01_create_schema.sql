/*
================================================================================
Project 5 — Meridian UAV Services: Predictive Maintenance
Script:  01_create_schema.sql
Purpose: Create the MeridianUAV database and its dimensional model.

BUSINESS QUESTION
    Which airframes need maintenance before their next mission?

THE SCHEMA DECISION THAT MAKES THE ANSWER POSSIBLE

    Wear is measured in STRESS-WEIGHTED DUTY CYCLES, not flight hours.

    The obvious model tracks hours flown and compares them with a service
    interval expressed in hours. Every maintenance system in the world does
    this, it is simple, and it is measuring the wrong thing: an hour of coastal
    survey in still air at 12kg payload does not wear a rotor the way an hour
    of mountain thermal work at 28kg does. Same hour on the meter, several
    times the damage.

    So Fact_Sortie carries the mission profile, the payload, the ambient
    conditions and the landing count, and Ref_StressModel converts those into a
    damage multiplier per flight hour. Wear becomes COMPUTABLE from what the
    aircraft actually did, rather than assumed from how long it was airborne.

    The consequence is the finding: a fleet that is fully compliant on the hour
    meter is not compliant on the thing the hour meter is standing in for.

TWO MORE DECISIONS WORTH THE COMMENT

    A component instance is tracked, not a component type. Fact_ComponentInstall
    follows one physical part onto an airframe and off again, so a rotor
    replaced at 200 hours starts its own life at zero. Tracking wear at
    airframe level would age a new part by its aircraft's history, and no
    maintenance decision made on that basis is sound.

    The stress model is a reference table with a SourceNote on every row. It is
    the most contestable input in the analysis -- a maintenance engineer will
    want to argue about whether mountain work is really 2.4x coastal -- so it
    lives where that argument can happen, not inside a CASE expression.

DATA DISCLOSURE
    Meridian UAV Services is a fictional operator. All data is synthetic and
    generated by 02_generate_synthetic_data.sql. The degradation patterns are
    modelled on publicly described behaviour of rotating machinery (bearing
    spectral signatures, brushless motor current signatures, Weibull wear-out);
    no proprietary reliability data is used and no claim is made about any real
    aircraft, operator or manufacturer.
================================================================================
*/

