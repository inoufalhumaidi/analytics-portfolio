DECLARE @missing VARCHAR(600) = '';
IF OBJECT_ID('dbo.Dim_Date','U')                IS NULL SET @missing += 'Dim_Date ';
IF OBJECT_ID('dbo.Dim_Base','U')                IS NULL SET @missing += 'Dim_Base ';
IF OBJECT_ID('dbo.Dim_Airframe','U')            IS NULL SET @missing += 'Dim_Airframe ';
IF OBJECT_ID('dbo.Dim_ComponentType','U')       IS NULL SET @missing += 'Dim_ComponentType ';
IF OBJECT_ID('dbo.Dim_MissionProfile','U')      IS NULL SET @missing += 'Dim_MissionProfile ';
IF OBJECT_ID('dbo.Fact_Sortie','U')             IS NULL SET @missing += 'Fact_Sortie ';
IF OBJECT_ID('dbo.Fact_ComponentInstall','U')   IS NULL SET @missing += 'Fact_ComponentInstall ';
IF OBJECT_ID('dbo.Fact_MaintenanceEvent','U')   IS NULL SET @missing += 'Fact_MaintenanceEvent ';
IF OBJECT_ID('dbo.Fact_SensorReading','U')      IS NULL SET @missing += 'Fact_SensorReading ';
IF OBJECT_ID('dbo.Ref_StressModel','U')         IS NULL SET @missing += 'Ref_StressModel ';
IF OBJECT_ID('dbo.Ref_ServiceInterval','U')     IS NULL SET @missing += 'Ref_ServiceInterval ';
IF OBJECT_ID('dbo.Ref_FleetTargets','U')        IS NULL SET @missing += 'Ref_FleetTargets ';
IF OBJECT_ID('dbo.Ref_Reporting','U')           IS NULL SET @missing += 'Ref_Reporting ';
IF @missing <> '' THROW 53001, 'FAILED to create the schema -- scroll up for the error.', 1;

-- Every mission profile must have a stress multiplier, or a sortie flown on it
-- would silently score zero damage.
IF EXISTS (SELECT 1 FROM dbo.Dim_MissionProfile p
           WHERE NOT EXISTS (SELECT 1 FROM dbo.Ref_StressModel s WHERE s.ProfileCode = p.ProfileCode))
    THROW 53002, 'Every mission profile needs a row in Ref_StressModel -- an unmodelled profile would accrue no wear.', 1;

-- Every component type must have an interval, for the same reason.
IF EXISTS (SELECT 1 FROM dbo.Dim_ComponentType c
           WHERE NOT EXISTS (SELECT 1 FROM dbo.Ref_ServiceInterval i WHERE i.ComponentCode = c.ComponentCode))
    THROW 53003, 'Every component type needs a row in Ref_ServiceInterval.', 1;

PRINT 'Schema created and verified: 5 dimensions, 4 facts, 4 reference tables.';
GO
