/*
Fact_Sortie -- one row per flight.

Carries what the aircraft actually DID, not merely how long it was up. Every
column here except duration exists because it changes how much damage the hour
does, and the stress model reads them.
*/
CREATE TABLE dbo.Fact_Sortie (
    SortieKey        INT IDENTITY(1,1) PRIMARY KEY,
    SortieID         VARCHAR(14) NOT NULL UNIQUE,
    AirframeKey      INT         NOT NULL,
    MissionProfileKey INT        NOT NULL,
    SortieDateKey    INT         NOT NULL,
    FlightMinutes    INT         NOT NULL,
    PayloadKg        DECIMAL(5,1) NOT NULL,
    -- Landings are a cycle count: take-off and landing load the airframe far
    -- more than cruise, so six short sorties are not one long one.
    Landings         TINYINT     NOT NULL,
    AmbientTempC     DECIMAL(4,1) NOT NULL,
    WindGustKts      DECIMAL(4,1) NOT NULL,
    CONSTRAINT FK_Sortie_Airframe FOREIGN KEY (AirframeKey)       REFERENCES dbo.Dim_Airframe(AirframeKey),
    CONSTRAINT FK_Sortie_Profile  FOREIGN KEY (MissionProfileKey) REFERENCES dbo.Dim_MissionProfile(MissionProfileKey),
    CONSTRAINT FK_Sortie_Date     FOREIGN KEY (SortieDateKey)     REFERENCES dbo.Dim_Date(DateKey)
);
GO
CREATE INDEX IX_Sortie_Airframe_Date ON dbo.Fact_Sortie (AirframeKey, SortieDateKey) INCLUDE (FlightMinutes, Landings, PayloadKg);
GO

/*
Fact_ComponentInstall -- one physical part, on one airframe, in one position.

The grain that makes remaining-life meaningful. A rotor fitted at the airframe's
400th hour starts its own life at zero; ageing it by the aircraft's history
would condemn a new part and clear a worn one.

RemovedDateKey NULL means still fitted.
*/
CREATE TABLE dbo.Fact_ComponentInstall (
    InstallKey        INT IDENTITY(1,1) PRIMARY KEY,
    ComponentSerial   VARCHAR(18) NOT NULL UNIQUE,
    ComponentTypeKey  INT         NOT NULL,
    AirframeKey       INT         NOT NULL,
    PositionNo        TINYINT     NOT NULL,
    InstalledDateKey  INT         NOT NULL,
    RemovedDateKey    INT         NULL,
    RemovalReason     VARCHAR(20) NULL
        CHECK (RemovalReason IN ('Scheduled','Failure','Precautionary','AirframeRetired')),
    CONSTRAINT FK_Install_Type     FOREIGN KEY (ComponentTypeKey) REFERENCES dbo.Dim_ComponentType(ComponentTypeKey),
    CONSTRAINT FK_Install_Airframe FOREIGN KEY (AirframeKey)      REFERENCES dbo.Dim_Airframe(AirframeKey),
    CONSTRAINT FK_Install_In       FOREIGN KEY (InstalledDateKey) REFERENCES dbo.Dim_Date(DateKey),
    CONSTRAINT FK_Install_Out      FOREIGN KEY (RemovedDateKey)   REFERENCES dbo.Dim_Date(DateKey)
);
GO
CREATE INDEX IX_Install_Airframe ON dbo.Fact_ComponentInstall (AirframeKey, ComponentTypeKey) INCLUDE (InstalledDateKey, RemovedDateKey);
GO

/*
Fact_MaintenanceEvent -- what was actually done, and why.

Scheduled and unscheduled are recorded in the same table with an EventType,
because the ratio between them is itself a KPI: a fleet doing mostly
unscheduled work is being maintained by its failures.
*/
CREATE TABLE dbo.Fact_MaintenanceEvent (
    EventKey        INT IDENTITY(1,1) PRIMARY KEY,
    EventID         VARCHAR(14) NOT NULL UNIQUE,
    AirframeKey     INT         NOT NULL,
    InstallKey      INT         NULL,        -- NULL = airframe-level work
    EventDateKey    INT         NOT NULL,
    EventType       VARCHAR(16) NOT NULL
        CHECK (EventType IN ('Scheduled','Unscheduled','Inspection')),
    -- Hours ON THE COMPONENT at the event, not on the airframe.
    ComponentHoursAtEvent DECIMAL(9,2) NULL,
    DowntimeHours   DECIMAL(6,1) NOT NULL,
    Finding         VARCHAR(200) NOT NULL,
    CONSTRAINT FK_Event_Airframe FOREIGN KEY (AirframeKey)  REFERENCES dbo.Dim_Airframe(AirframeKey),
    CONSTRAINT FK_Event_Install  FOREIGN KEY (InstallKey)   REFERENCES dbo.Fact_ComponentInstall(InstallKey),
    CONSTRAINT FK_Event_Date     FOREIGN KEY (EventDateKey) REFERENCES dbo.Dim_Date(DateKey)
);
GO

/*
Fact_SensorReading -- post-sortie condition monitoring, one row per component
instance per sortie.

Deliberately at SORTIE grain rather than raw telemetry: the downloaded summary
is what an operator of this size actually keeps, and a model trained on what
exists is worth more than one trained on data nobody has.
*/
CREATE TABLE dbo.Fact_SensorReading (
    ReadingKey      INT IDENTITY(1,1) PRIMARY KEY,
    SortieKey       INT          NOT NULL,
    InstallKey      INT          NOT NULL,
    -- RMS vibration in the bearing band. The classic wear-out signal, and the
    -- one that rises earliest.
    VibrationRms    DECIMAL(7,4) NOT NULL,
    -- Peak winding temperature above ambient, so the measure is comparable
    -- between a January sortie and an August one.
    TempRiseC       DECIMAL(5,2) NOT NULL,
    -- Current drawn for the same commanded thrust: rises as bearings stiffen.
    CurrentDrawA    DECIMAL(6,3) NOT NULL,
    CONSTRAINT FK_Reading_Sortie  FOREIGN KEY (SortieKey)  REFERENCES dbo.Fact_Sortie(SortieKey),
    CONSTRAINT FK_Reading_Install FOREIGN KEY (InstallKey) REFERENCES dbo.Fact_ComponentInstall(InstallKey)
);
GO
CREATE INDEX IX_Reading_Install ON dbo.Fact_SensorReading (InstallKey, SortieKey) INCLUDE (VibrationRms, TempRiseC, CurrentDrawA);
GO

-- =============================================================================
-- REFERENCE TABLES
-- The contestable inputs. Each lives here rather than inside a query so that
-- the engineer who disagrees can find it, argue with it and change it.
-- =============================================================================

/*
Ref_StressModel -- the damage multiplier per flight hour, by mission profile.

The single most contestable input in this project. A maintenance engineer will
want to argue about whether mountain work really costs 2.4 times coastal, and
that argument is the right one to be having -- so the number sits in a table
with its reasoning attached rather than buried in a CASE expression where
nobody can see it to disagree.
*/
/*
WHAT THIS TABLE DELIBERATELY DOES NOT REPRESENT

It is keyed on the mission profile alone. There is no component dimension, so a
landing costs a rotor assembly exactly what it costs the landing gear.

Physically that is wrong, and it is stated here rather than left for a reader to
discover. Modelling per-component damage coefficients would need six times the
reference data and a source for each cell, and this project has no such source.
What the model does support is the comparison it was built for: two airframes
flying different work accrue different damage per logged hour. That conclusion
does not depend on the missing dimension.

The consequence to be aware of when reading results by component: differences in
unscheduled rate BETWEEN component types come from their Weibull shapes and
intervals, not from any component-specific response to landings.
*/
CREATE TABLE dbo.Ref_StressModel (
    ProfileCode       VARCHAR(12)  NOT NULL PRIMARY KEY,
    StressMultiplier  DECIMAL(5,3) NOT NULL,
    -- Additional damage per landing, expressed in equivalent flight hours.
    CyclePenaltyHours DECIMAL(5,3) NOT NULL,
    -- Additional damage per kg of payload above the nominal 12kg, per hour.
    PayloadPenaltyPerKg DECIMAL(6,4) NOT NULL,
    -- 400, not 220. These notes carry the ARGUMENT for a coefficient that moves
    -- every figure in the project, and a column too narrow to hold the argument
    -- is a column that quietly encourages leaving it out. Third truncation of
    -- this kind in this portfolio; the pattern is always the same -- the
    -- reasoning outgrows a width chosen before the reasoning existed.
    SourceNote        VARCHAR(400) NOT NULL
);
GO

/*
Ref_ServiceInterval -- the interval, expressed BOTH ways.

Both columns exist so the two can be compared, which is the whole point. The
hour interval is what the maintenance system enforces today; the cycle interval
is what the manufacturer's data actually supports once stress is accounted for.
*/
CREATE TABLE dbo.Ref_ServiceInterval (
    ComponentCode          VARCHAR(12)  NOT NULL PRIMARY KEY,
    IntervalFlightHours    DECIMAL(7,1) NOT NULL,
    IntervalStressHours    DECIMAL(7,1) NOT NULL,
    -- Weibull shape. Above 1 means wear-out: failure rate RISES with age, and
    -- the mean time between failures is the wrong statistic for scheduling.
    WeibullShape           DECIMAL(4,2) NOT NULL,
    IntervalNote           VARCHAR(400) NOT NULL
);
GO

/*
Ref_Reporting -- the settings that decide WHICH question gets answered.

These are not cosmetic. Each one silently changes every figure the project
publishes, so each one sits in a table with its reasoning attached rather than
as a literal inside a query.

ReportingAsOfDate in particular. Anchoring on 'the latest date in the data'
looks harmless and means the published answer moves the moment anyone loads one
more sortie -- so a figure quoted in a report stops matching the system that
produced it, and nobody can tell whether the fleet changed or the anchor did.
*/
CREATE TABLE dbo.Ref_Reporting (
    SettingName   VARCHAR(40)  NOT NULL PRIMARY KEY,
    SettingValue  VARCHAR(40)  NOT NULL,
    -- 400, not 300. These descriptions carry the reasoning for a setting that
    -- moves every published figure; a column too narrow to hold the reasoning
    -- is a column that quietly encourages leaving it out.
    [Description] VARCHAR(400) NOT NULL
);
GO

CREATE TABLE dbo.Ref_FleetTargets (
    MetricName    VARCHAR(40)   NOT NULL PRIMARY KEY,
    TargetValue   DECIMAL(10,2) NOT NULL,
    WarningValue  DECIMAL(10,2) NOT NULL,
    Direction     VARCHAR(15)   NOT NULL CHECK (Direction IN ('HigherBetter','LowerBetter')),
    Unit          VARCHAR(10)   NOT NULL CHECK (Unit IN ('Percent','Count','Hours','Ratio')),
    [Description] VARCHAR(220)  NOT NULL
);
GO

