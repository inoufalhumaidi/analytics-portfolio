CREATE TABLE dbo.Dim_Date (
    DateKey      INT          NOT NULL PRIMARY KEY,   -- YYYYMMDD
    [Date]       DATE         NOT NULL UNIQUE,
    [Year]       SMALLINT     NOT NULL,
    [Quarter]    TINYINT      NOT NULL,
    [Month]      TINYINT      NOT NULL,
    MonthName    VARCHAR(12)  NOT NULL,
    YearMonth    CHAR(7)      NOT NULL,
    YearQuarter  CHAR(7)      NOT NULL,
    MonthEndDate DATE         NOT NULL,
    IsMonthEnd   BIT          NOT NULL,
    IsWeekend    BIT          NOT NULL
);
GO

CREATE TABLE dbo.Dim_Base (
    BaseKey    INT IDENTITY(1,1) PRIMARY KEY,
    BaseCode   VARCHAR(8)   NOT NULL UNIQUE,
    BaseName   VARCHAR(50)  NOT NULL,
    Region     VARCHAR(30)  NOT NULL,
    -- Hangar slots are the scarce resource. A maintenance queue that ignores
    -- them is a wish list: you cannot service eleven airframes in a week with
    -- three bays whatever the risk score says.
    HangarBays TINYINT      NOT NULL
);
GO

CREATE TABLE dbo.Dim_Airframe (
    AirframeKey     INT IDENTITY(1,1) PRIMARY KEY,
    TailNumber      VARCHAR(10)  NOT NULL UNIQUE,   -- e.g. MU-014
    ModelCode       VARCHAR(12)  NOT NULL,
    BaseKey         INT          NOT NULL,
    InServiceDateKey INT         NOT NULL,
    -- Airframes retired mid-window are not failures to maintain, and counting
    -- them as unserviced would overstate the backlog.
    AirframeStatus  VARCHAR(12)  NOT NULL
        CHECK (AirframeStatus IN ('Active','Retired')),
    RetiredDateKey  INT          NULL,
    CONSTRAINT FK_Airframe_Base FOREIGN KEY (BaseKey)          REFERENCES dbo.Dim_Base(BaseKey),
    CONSTRAINT FK_Airframe_InSvc FOREIGN KEY (InServiceDateKey) REFERENCES dbo.Dim_Date(DateKey),
    CONSTRAINT FK_Airframe_Retired FOREIGN KEY (RetiredDateKey) REFERENCES dbo.Dim_Date(DateKey)
);
GO

CREATE TABLE dbo.Dim_ComponentType (
    ComponentTypeKey INT IDENTITY(1,1) PRIMARY KEY,
    ComponentCode    VARCHAR(12)  NOT NULL UNIQUE,
    ComponentName    VARCHAR(50)  NOT NULL,
    -- How many of this component each airframe carries. Four rotor assemblies,
    -- one battery pack, and so on -- so a fleet count is not a component count.
    PositionsPerAirframe TINYINT  NOT NULL,
    -- Criticality drives whether a failure grounds the aircraft or degrades it.
    Criticality      VARCHAR(16)  NOT NULL
        CHECK (Criticality IN ('FlightCritical','MissionCritical','Degraded')),
    -- Lead time to obtain and fit. A prediction that arrives inside this window
    -- is not actionable, and that distinction is the second finding of this
    -- project.
    LeadTimeFlightHours DECIMAL(6,1) NOT NULL
);
GO

CREATE TABLE dbo.Dim_MissionProfile (
    MissionProfileKey INT IDENTITY(1,1) PRIMARY KEY,
    ProfileCode       VARCHAR(12)  NOT NULL UNIQUE,
    ProfileName       VARCHAR(50)  NOT NULL,
    TypicalPayloadKg  DECIMAL(5,1) NOT NULL,
    [Description]     VARCHAR(200) NOT NULL
);
GO

