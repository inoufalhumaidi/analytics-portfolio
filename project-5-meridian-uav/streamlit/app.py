    st.dataframe(summary, width="stretch", hide_index=True)

    st.subheader("The gate")
    st.markdown(
        "The gate does not count defective rows. It asks what share of **flight-critical "
        "components fitted right now** would answer differently if the flagged data were "
        "corrected - comparing each component's uncertainty band against its margin to "
        "the threshold.\n\n"
        "A duplicated sortie from March 2024 is a real defect and completely irrelevant, "
        "because the component it inflated has been replaced twice since. Counting it "
        "would make a harmless problem look the same size as a real one."
    )

    st.subheader("Every finding")
    pick = st.multiselect("Check", sorted(findings["CheckCode"].unique()))
    view = findings[findings["CheckCode"].isin(pick)] if pick else findings
    st.dataframe(
        view[["CheckCode", "Severity", "EntityType", "EntityRef", "Detail", "AffectsCurrentWear"]],
        width="stretch", hide_index=True,
    )
