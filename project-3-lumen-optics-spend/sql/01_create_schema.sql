/*
================================================================================
Project 3 -- Lumen Optics Manufacturing: Photonics Spend Scorecard
Script:  01_create_schema.sql
Purpose: Creates the LumenSpend database -- a star schema for direct-materials
         procurement in a photonics manufacturer, plus the reference tables
         that drive every downstream threshold and assumption.

Business question:
   "Our purchase prices are flat or falling and every variance report is green
    -- so why is material cost per ACCEPTED unit rising, and which
    supplier-part combinations should sourcing renegotiate first?"

THREE MODELLING DECISIONS WORTH STATING UP FRONT

  1. A PRICE AGREEMENT IS A FACT, NOT AN ATTRIBUTE.
     A contracted price is true between two dates and false outside them.
     Storing it as a column on the part or the vendor would make today's
     contract retroactively govern a purchase made two years ago, so every
     historical price variance would be measured against a price that did not
     exist at the time. Fact_PriceAgreement is therefore dated, and purchase
     price variance joins on the agreement in force at the ORDER date.

  2. RECEIPTS CARRY ACCEPTANCE, NOT JUST QUANTITY.
     In optics a component can arrive, be counted, and still be unusable --
     surface figure out of spec, coating defects, fibre attenuation above
     tolerance. If a receipt records only quantity, then the cheapest supplier
     by unit price always wins, because the cost of what they shipped that
     could not be used is invisible. Splitting QtyAccepted from QtyRejected is
     what makes cost per ACCEPTED unit computable.

  3. EXPECTED PRICE EROSION IS A REFERENCE TABLE, NOT A CONSTANT IN A QUERY.
     Photonic components follow learning curves: unit prices decline as
     volumes rise and processes mature. That expectation is an ASSUMPTION, it
     varies by category, and it is the single most contestable input in this
     analysis -- so it lives in Ref_PriceErosionBenchmark where a category
     manager can see it, challenge it and change it, rather than buried in a
     CASE expression where nobody will ever find it.

DATA DISCLOSURE: Lumen Optics Manufacturing is a fictional company. All data
loaded into this schema is synthetically generated by
02_generate_synthetic_data.sql. No confidential, proprietary, or production
data of any real organization is used or represented.
================================================================================
*/

