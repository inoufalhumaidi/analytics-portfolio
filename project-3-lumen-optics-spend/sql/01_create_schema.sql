-- =============================================================================
-- REFERENCE: Ref_PriceErosionBenchmark
--
-- The most contestable input in the whole project, so it is visible and
-- editable rather than hidden in a query -- see modelling decision 3.
--
-- Photonic components follow learning curves: as cumulative volume rises and
-- processes mature, unit cost falls. A supplier holding price FLAT across three
-- years of a declining category is extracting margin quietly, and no variance
-- report catches it because the price never went up.
--
-- SourceNote records where each figure came from, because an assumption without
-- a provenance is an opinion, and the first question a category manager will
-- ask is "says who?".
-- =============================================================================
CREATE TABLE dbo.Ref_PriceErosionBenchmark (
    Category               VARCHAR(30)  NOT NULL PRIMARY KEY,
    AnnualErosionPct       DECIMAL(5,2) NOT NULL,
    ToleranceBandPct       DECIMAL(5,2) NOT NULL,
    MaturityProfile        VARCHAR(12)  NOT NULL CHECK (MaturityProfile IN ('Emerging','Maturing','Mature')),
    SourceNote             VARCHAR(160) NOT NULL
);
GO

