-- =============================================================================
-- DIMENSION: Dim_Date
-- Covers order dates, promised dates, receipt dates and agreement validity.
-- =============================================================================
CREATE TABLE dbo.Dim_Date (
    DateKey      INT          NOT NULL PRIMARY KEY,   -- YYYYMMDD
    [Date]       DATE         NOT NULL UNIQUE,
    [Year]       SMALLINT     NOT NULL,
    [Quarter]    TINYINT      NOT NULL,
    [Month]      TINYINT      NOT NULL,
    MonthName    VARCHAR(12)  NOT NULL,
    YearMonth    CHAR(7)      NOT NULL,
    YearQuarter  CHAR(7)      NOT NULL,
    MonthEndDate DATE         NOT NULL,
    IsMonthEnd   BIT          NOT NULL,
    IsWeekend    BIT          NOT NULL
);
GO
CREATE INDEX IX_DimDate_Date      ON dbo.Dim_Date([Date]);
CREATE INDEX IX_DimDate_YearMonth ON dbo.Dim_Date(YearMonth);
GO

-- =============================================================================
-- DIMENSION: Dim_Buyer  (the sourcing team; a category manager owns categories)
-- =============================================================================
CREATE TABLE dbo.Dim_Buyer (
    BuyerKey     INT IDENTITY(1,1) PRIMARY KEY,
    BuyerID      VARCHAR(10)  NOT NULL UNIQUE,
    BuyerName    VARCHAR(60)  NOT NULL,
    Team         VARCHAR(30)  NOT NULL,
    IsActive     BIT          NOT NULL DEFAULT 1
);
GO

-- =============================================================================
-- DIMENSION: Dim_Vendor
--
-- RelationshipStartDate exists because leverage is partly a function of history:
-- a supplier three months into a first contract negotiates differently from one
-- eight years in. LumenRevenueSharePct is our estimate of how much of THEIR
-- revenue we represent -- the single most useful leverage signal in sourcing,
-- and the reason a large spend with a huge supplier can carry less weight than
-- a small spend with a small one.
-- =============================================================================
CREATE TABLE dbo.Dim_Vendor (
    VendorKey            INT IDENTITY(1,1) PRIMARY KEY,
    VendorID             VARCHAR(10)   NOT NULL UNIQUE,
    VendorName           VARCHAR(80)   NOT NULL,
    Country              VARCHAR(30)   NOT NULL,
    VendorTier           VARCHAR(15)   NOT NULL CHECK (VendorTier IN ('Strategic','Preferred','Approved','Transactional')),
    RelationshipStartDate DATE         NOT NULL,
    LumenRevenueSharePct DECIMAL(5,2)  NOT NULL CHECK (LumenRevenueSharePct BETWEEN 0 AND 100),
    IsActive             BIT           NOT NULL DEFAULT 1
);
GO
CREATE INDEX IX_DimVendor_Tier ON dbo.Dim_Vendor(VendorTier);
GO

-- =============================================================================
-- DIMENSION: Dim_Part
--
-- QualificationMonths and QualifiedSupplierCount together decide whether
-- sourcing has any leverage at all. A sole-source photonic component with a
-- nine-month requalification cannot be renegotiated by threatening to leave --
-- there is nowhere to go inside the planning horizon. Recording both stops the
-- priority queue from recommending a negotiation that cannot be won, which is
-- the fastest way to lose a sourcing team's trust in a report.
-- =============================================================================
CREATE TABLE dbo.Dim_Part (
    PartKey                 INT IDENTITY(1,1) PRIMARY KEY,
    PartNumber              VARCHAR(20)  NOT NULL UNIQUE,
    PartName                VARCHAR(80)  NOT NULL,
    Category                VARCHAR(30)  NOT NULL CHECK (Category IN
                              ('Laser Diode','Photodetector','Optical Fibre','Lens Assembly',
                               'Optical Coating','Precision Mount','Fibre Connector','Thermal Control')),
    UnitOfMeasure           VARCHAR(10)  NOT NULL,
    Criticality             VARCHAR(10)  NOT NULL CHECK (Criticality IN ('Critical','Standard','Commodity')),
    QualifiedSupplierCount  TINYINT      NOT NULL CHECK (QualifiedSupplierCount >= 1),
    QualificationMonths     TINYINT      NOT NULL CHECK (QualificationMonths >= 0),
    FirstPurchaseDate       DATE         NOT NULL
);
GO
CREATE INDEX IX_DimPart_Category ON dbo.Dim_Part(Category);
GO

-- =============================================================================
-- FACT: Fact_PriceAgreement  (grain: one negotiated price for one part from one
-- vendor, valid between two dates)
--
-- Dated on purpose -- see modelling decision 1 in the header. ValidToDateKey is
-- NULL for an open-ended agreement, and the lookup must treat NULL as "still in
-- force" rather than excluding it, which is the usual way a dated-join bug
-- makes contract coverage look far worse than it is.
-- =============================================================================
CREATE TABLE dbo.Fact_PriceAgreement (
    AgreementKey     INT IDENTITY(1,1) PRIMARY KEY,
    AgreementNo      VARCHAR(15)   NOT NULL UNIQUE,
    VendorKey        INT           NOT NULL REFERENCES dbo.Dim_Vendor(VendorKey),
    PartKey          INT           NOT NULL REFERENCES dbo.Dim_Part(PartKey),
    ValidFromDateKey INT           NOT NULL REFERENCES dbo.Dim_Date(DateKey),
    ValidToDateKey   INT           NULL     REFERENCES dbo.Dim_Date(DateKey),
    AgreedUnitPrice  DECIMAL(12,4) NOT NULL CHECK (AgreedUnitPrice > 0),
    MinOrderQty      INT           NOT NULL DEFAULT 1,
    CHECK (ValidToDateKey IS NULL OR ValidToDateKey >= ValidFromDateKey)
);
GO
CREATE INDEX IX_Agreement_PartVendor ON dbo.Fact_PriceAgreement(PartKey, VendorKey);
GO

-- =============================================================================
-- FACT: Fact_PurchaseOrderLine  (grain: one line on one purchase order)
--
-- Freight and expedite are held per LINE, not netted into the unit price,
-- because they answer different questions and have different owners. A unit
-- price is negotiated with the supplier; an expedite fee is caused by planning.
-- Folding them together hides which of the two is costing the money, and it is
-- usually the one nobody is looking at.
-- =============================================================================
CREATE TABLE dbo.Fact_PurchaseOrderLine (
    POLineKey        BIGINT IDENTITY(1,1) PRIMARY KEY,
    PONumber         VARCHAR(15)   NOT NULL,
    POLineNo         SMALLINT      NOT NULL,
    PartKey          INT           NOT NULL REFERENCES dbo.Dim_Part(PartKey),
    VendorKey        INT           NOT NULL REFERENCES dbo.Dim_Vendor(VendorKey),
    BuyerKey         INT           NOT NULL REFERENCES dbo.Dim_Buyer(BuyerKey),
    OrderDateKey     INT           NOT NULL REFERENCES dbo.Dim_Date(DateKey),
    PromisedDateKey  INT           NOT NULL REFERENCES dbo.Dim_Date(DateKey),
    OrderQty         INT           NOT NULL CHECK (OrderQty > 0),
    UnitPrice        DECIMAL(12,4) NOT NULL CHECK (UnitPrice > 0),
    FreightAmount    DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (FreightAmount >= 0),
    ExpediteFee      DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (ExpediteFee >= 0),
    IsExpedited      BIT           NOT NULL DEFAULT 0,
    CONSTRAINT UQ_POLine UNIQUE (PONumber, POLineNo),
    CHECK (PromisedDateKey >= OrderDateKey),
    -- an expedite fee without the flag, or the flag without a fee, is a data
    -- defect the quality layer looks for; the constraint permits neither
    CHECK ((IsExpedited = 1 AND ExpediteFee > 0) OR (IsExpedited = 0 AND ExpediteFee = 0))
);
GO
CREATE INDEX IX_POLine_Part      ON dbo.Fact_PurchaseOrderLine(PartKey);
CREATE INDEX IX_POLine_Vendor    ON dbo.Fact_PurchaseOrderLine(VendorKey);
CREATE INDEX IX_POLine_OrderDate ON dbo.Fact_PurchaseOrderLine(OrderDateKey);
GO

-- =============================================================================
-- FACT: Fact_GoodsReceipt  (grain: one receipt against one purchase order line)
--
-- A line may be received in several deliveries, so this is not one-to-one with
-- the order line. QtyAccepted + QtyRejected = QtyReceived is enforced here
-- rather than assumed downstream: a receipt whose parts do not add up makes
-- every yield figure wrong in a way no totals check would notice.
-- =============================================================================
CREATE TABLE dbo.Fact_GoodsReceipt (
    ReceiptKey       BIGINT IDENTITY(1,1) PRIMARY KEY,
    ReceiptNo        VARCHAR(15)   NOT NULL UNIQUE,
    POLineKey        BIGINT        NOT NULL REFERENCES dbo.Fact_PurchaseOrderLine(POLineKey),
    ReceiptDateKey   INT           NOT NULL REFERENCES dbo.Dim_Date(DateKey),
    QtyReceived      INT           NOT NULL CHECK (QtyReceived > 0),
    QtyAccepted      INT           NOT NULL CHECK (QtyAccepted >= 0),
    QtyRejected      INT           NOT NULL CHECK (QtyRejected >= 0),
    RejectReasonCode VARCHAR(20)   NULL,
    CHECK (QtyAccepted + QtyRejected = QtyReceived),
    CHECK ((QtyRejected = 0 AND RejectReasonCode IS NULL)
        OR (QtyRejected > 0 AND RejectReasonCode IS NOT NULL))
);
GO
CREATE INDEX IX_Receipt_POLine ON dbo.Fact_GoodsReceipt(POLineKey);
CREATE INDEX IX_Receipt_Date   ON dbo.Fact_GoodsReceipt(ReceiptDateKey);
GO

-- =============================================================================
-- REFERENCE: Ref_RejectReason
-- Photonics-specific failure modes. Grouped by whether the cause sits with the
-- supplier or with us, because only the first is negotiable.
