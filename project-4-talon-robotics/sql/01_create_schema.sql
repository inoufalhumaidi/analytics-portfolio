/*
Ref_VerificationPolicy -- what counts as evidence.

The single most contestable input in this project. A safety requirement is not
verified by a unit test, and saying so in a CASE expression buried in a view
means the rule is invisible to the systems engineer whose judgement it encodes.

MinTestLevel is ordered: Unit < Integration < HIL < Field. A test at or above
the minimum grade is sufficient evidence.
*/
CREATE TABLE dbo.Ref_VerificationPolicy (
    ReqType          VARCHAR(16) NOT NULL PRIMARY KEY,
    MinTestLevel     VARCHAR(16) NOT NULL
        CHECK (MinTestLevel IN ('Unit','Integration','HIL','Field')),
    MinTestLevelRank TINYINT     NOT NULL,   -- 1..4, so SQL can compare grades
    RequiresIndependentTester BIT NOT NULL,  -- the author may not verify their own work
    PolicyNote       VARCHAR(220) NOT NULL
);
GO

CREATE TABLE dbo.Ref_TestLevelRank (
    TestLevel     VARCHAR(16) NOT NULL PRIMARY KEY,
    LevelRank     TINYINT     NOT NULL UNIQUE,
    RigHours      DECIMAL(5,2) NOT NULL,     -- scarce-resource cost of one run
    LevelNote     VARCHAR(160) NOT NULL
);
GO

CREATE TABLE dbo.Ref_RAIDMatrix (
    Probability   TINYINT     NOT NULL,
    Impact        TINYINT     NOT NULL,
    ExposureScore TINYINT     NOT NULL,
    ExposureBand  VARCHAR(10) NOT NULL
        CHECK (ExposureBand IN ('Low','Medium','High','Critical')),
    CONSTRAINT PK_RAIDMatrix PRIMARY KEY (Probability, Impact)
);
GO

CREATE TABLE dbo.Ref_ReadinessTargets (
    MetricName    VARCHAR(40)   NOT NULL PRIMARY KEY,
    TargetValue   DECIMAL(10,2) NOT NULL,
    WarningValue  DECIMAL(10,2) NOT NULL,
    Direction     VARCHAR(15)   NOT NULL CHECK (Direction IN ('HigherBetter','LowerBetter')),
    Unit          VARCHAR(10)   NOT NULL CHECK (Unit IN ('Percent','Count','Hours','Score')),
    [Description] VARCHAR(220)  NOT NULL
);
GO

