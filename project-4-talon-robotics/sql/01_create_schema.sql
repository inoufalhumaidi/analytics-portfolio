/*
Fact_TestRun -- the evidence. One row per execution of one test case against
one build.

BuildKey is the point of the whole model. A result without a build is an
opinion: it tells you something passed once, not whether it passes on the
thing you are about to ship.
*/
CREATE TABLE dbo.Fact_TestRun (
    TestRunKey   INT IDENTITY(1,1) PRIMARY KEY,
    TestCaseKey  INT         NOT NULL,
    BuildKey     INT         NOT NULL,
    RunDateKey   INT         NOT NULL,
    RunByKey     INT         NOT NULL,
    Result       VARCHAR(10) NOT NULL
        CHECK (Result IN ('Pass','Fail','Blocked')),
    DurationMin  INT         NOT NULL,
    CONSTRAINT FK_Run_TC    FOREIGN KEY (TestCaseKey) REFERENCES dbo.Dim_TestCase(TestCaseKey),
    CONSTRAINT FK_Run_Build FOREIGN KEY (BuildKey)    REFERENCES dbo.Dim_Build(BuildKey),
    CONSTRAINT FK_Run_Date  FOREIGN KEY (RunDateKey)  REFERENCES dbo.Dim_Date(DateKey),
    CONSTRAINT FK_Run_By    FOREIGN KEY (RunByKey)    REFERENCES dbo.Dim_Person(PersonKey)
);
GO
CREATE INDEX IX_TestRun_Case_Build ON dbo.Fact_TestRun (TestCaseKey, BuildKey) INCLUDE (Result, RunDateKey);
GO

/*
Fact_BuildSubsystemChange -- what each build actually touched.

Without this, staleness cannot be distinguished from age. A verification from
six months ago is perfectly good if nothing underneath it has moved; a
verification from last week is worthless if the subsystem was rewritten on
Monday. Elapsed time is not the question -- intervening change is.
*/
CREATE TABLE dbo.Fact_BuildSubsystemChange (
    BuildKey     INT NOT NULL,
    SubsystemKey INT NOT NULL,
    -- Lines changed is a proxy for "how much moved". It is deliberately not
    -- used as a threshold: any change at all invalidates a verification. It is
    -- carried so a reviewer can see the size of what invalidated it.
    LinesChanged INT NOT NULL,
    CONSTRAINT PK_BuildSubsystemChange PRIMARY KEY (BuildKey, SubsystemKey),
    CONSTRAINT FK_BSC_Build     FOREIGN KEY (BuildKey)     REFERENCES dbo.Dim_Build(BuildKey),
    CONSTRAINT FK_BSC_Subsystem FOREIGN KEY (SubsystemKey) REFERENCES dbo.Dim_Subsystem(SubsystemKey)
);
GO

/*
Fact_RequirementChange -- when the requirement itself moved.

A requirement reworded after it was verified is as stale as one whose code
changed: the test may now be checking the wrong sentence. Clarifications are
recorded separately from modifications because only one of them invalidates
evidence, and conflating them would either overstate staleness or hide it.
*/
CREATE TABLE dbo.Fact_RequirementChange (
    RequirementChangeKey INT IDENTITY(1,1) PRIMARY KEY,
    RequirementKey INT         NOT NULL,
    ChangeDateKey  INT         NOT NULL,
    BuildKey       INT         NOT NULL,   -- the build current when the change landed
    ChangeType     VARCHAR(14) NOT NULL
        CHECK (ChangeType IN ('Modified','Clarified')),
    ChangedByKey   INT         NOT NULL,
    ChangeNote     VARCHAR(200) NOT NULL,
    CONSTRAINT FK_RC_Req   FOREIGN KEY (RequirementKey) REFERENCES dbo.Dim_Requirement(RequirementKey),
    CONSTRAINT FK_RC_Date  FOREIGN KEY (ChangeDateKey)  REFERENCES dbo.Dim_Date(DateKey),
    CONSTRAINT FK_RC_Build FOREIGN KEY (BuildKey)       REFERENCES dbo.Dim_Build(BuildKey),
    CONSTRAINT FK_RC_By    FOREIGN KEY (ChangedByKey)   REFERENCES dbo.Dim_Person(PersonKey)
);
GO

/*
Fact_WorkItem -- the flattering number.

This is where "94% complete" comes from: closed work items over total work
items. It is a real metric that real programmes report, and it is not a lie.
It is simply not an answer to "can we ship", because it counts effort rather
than evidence. It is modelled so the two can be put side by side.
*/
CREATE TABLE dbo.Fact_WorkItem (
    WorkItemKey    INT IDENTITY(1,1) PRIMARY KEY,
    WorkItemID     VARCHAR(12) NOT NULL UNIQUE,
    RequirementKey INT         NOT NULL,
    AssignedToKey  INT         NOT NULL,
    OpenedDateKey  INT         NOT NULL,
    ClosedDateKey  INT         NULL,
    EstimateHours  DECIMAL(6,1) NOT NULL,
    ActualHours    DECIMAL(6,1) NULL,
    WorkItemStatus VARCHAR(12) NOT NULL
        CHECK (WorkItemStatus IN ('Open','InProgress','Closed')),
    CONSTRAINT FK_WI_Req    FOREIGN KEY (RequirementKey) REFERENCES dbo.Dim_Requirement(RequirementKey),
    CONSTRAINT FK_WI_Person FOREIGN KEY (AssignedToKey)  REFERENCES dbo.Dim_Person(PersonKey),
    CONSTRAINT FK_WI_Opened FOREIGN KEY (OpenedDateKey)  REFERENCES dbo.Dim_Date(DateKey),
    CONSTRAINT FK_WI_Closed FOREIGN KEY (ClosedDateKey)  REFERENCES dbo.Dim_Date(DateKey)
);
GO

/*
Fact_RAID -- Risks, Assumptions, Issues, Dependencies.

Exposure is probability x impact, both read from Ref_RAIDMatrix rather than
hardcoded, so a programme board can re-score the matrix without a code change.

ClosedDateKey is nullable and OwnerKey is NOT nullable on purpose: an
unowned risk is the most common way a RAID log becomes decorative, so the
schema makes it impossible to raise one without an owner, and the data-quality
layer then looks for owners who have left or are overloaded instead.
*/
CREATE TABLE dbo.Fact_RAID (
    RAIDKey       INT IDENTITY(1,1) PRIMARY KEY,
    RAIDID        VARCHAR(12) NOT NULL UNIQUE,
    RAIDType      VARCHAR(12) NOT NULL
        CHECK (RAIDType IN ('Risk','Assumption','Issue','Dependency')),
    Title         VARCHAR(160) NOT NULL,
    SubsystemKey  INT         NOT NULL,
    OwnerKey      INT         NOT NULL,
    RaisedDateKey INT         NOT NULL,
    DueDateKey    INT         NULL,
    ClosedDateKey INT         NULL,
    Probability   TINYINT     NOT NULL CHECK (Probability BETWEEN 1 AND 5),
    Impact        TINYINT     NOT NULL CHECK (Impact      BETWEEN 1 AND 5),
    RAIDStatus    VARCHAR(12) NOT NULL
        CHECK (RAIDStatus IN ('Open','Mitigating','Closed')),
    MitigationNote VARCHAR(250) NOT NULL,
    CONSTRAINT FK_RAID_Subsystem FOREIGN KEY (SubsystemKey)  REFERENCES dbo.Dim_Subsystem(SubsystemKey),
    CONSTRAINT FK_RAID_Owner     FOREIGN KEY (OwnerKey)      REFERENCES dbo.Dim_Person(PersonKey),
    CONSTRAINT FK_RAID_Raised    FOREIGN KEY (RaisedDateKey) REFERENCES dbo.Dim_Date(DateKey),
    CONSTRAINT FK_RAID_Due       FOREIGN KEY (DueDateKey)    REFERENCES dbo.Dim_Date(DateKey),
    CONSTRAINT FK_RAID_Closed    FOREIGN KEY (ClosedDateKey) REFERENCES dbo.Dim_Date(DateKey)
);
GO

-- =============================================================================
-- REFERENCE TABLES
-- The contestable inputs. Each lives here rather than inside a query so that
-- the person who disagrees with it can find it, argue with it and change it.
