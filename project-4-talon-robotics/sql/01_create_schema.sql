CREATE TABLE dbo.Dim_Date (
    DateKey      INT          NOT NULL PRIMARY KEY,   -- YYYYMMDD
    [Date]       DATE         NOT NULL UNIQUE,
    [Year]       SMALLINT     NOT NULL,
    [Quarter]    TINYINT      NOT NULL,
    [Month]      TINYINT      NOT NULL,
    MonthName    VARCHAR(12)  NOT NULL,
    YearMonth    CHAR(7)      NOT NULL,
    YearQuarter  CHAR(7)      NOT NULL,
    MonthEndDate DATE         NOT NULL,
    IsMonthEnd   BIT          NOT NULL,
    IsWeekend    BIT          NOT NULL,
    IsWorkday    BIT          NOT NULL
);
GO

CREATE TABLE dbo.Dim_Subsystem (
    SubsystemKey  INT IDENTITY(1,1) PRIMARY KEY,
    SubsystemCode VARCHAR(12)  NOT NULL UNIQUE,
    SubsystemName VARCHAR(60)  NOT NULL,
    -- Criticality drives which verification level the policy demands, and it
    -- drives the ship gate. A payload release cannot be held on a cosmetic
    -- defect in ground software, and cannot ship on an unverified release
    -- mechanism.
    Criticality   VARCHAR(12)  NOT NULL
        CHECK (Criticality IN ('Safety', 'Mission', 'Support')),
    -- Hardware-in-the-loop time is the scarce resource in this programme, so
    -- the queue has to know which subsystems compete for it.
    RequiresHILRig BIT         NOT NULL,
    LeadEngineerID VARCHAR(10) NOT NULL
);
GO

CREATE TABLE dbo.Dim_Person (
    PersonKey  INT IDENTITY(1,1) PRIMARY KEY,
    PersonID   VARCHAR(10)  NOT NULL UNIQUE,
    PersonName VARCHAR(60)  NOT NULL,
    [Role]     VARCHAR(24)  NOT NULL
        CHECK ([Role] IN ('Systems Engineer','Software Engineer','Test Engineer',
                          'Quality Engineer','Project Manager','Hardware Engineer')),
    Team       VARCHAR(30)  NOT NULL,
    -- Verification capacity per week, in test-hours. The priority queue is
    -- bounded by this: a list of everything outstanding is not a plan.
    WeeklyCapacityHours DECIMAL(5,1) NOT NULL
);
GO

CREATE TABLE dbo.Dim_Build (
    BuildKey        INT IDENTITY(1,1) PRIMARY KEY,
    BuildID         VARCHAR(12) NOT NULL UNIQUE,     -- e.g. B-0042
    BuildNumber     INT         NOT NULL UNIQUE,     -- monotonic; ordering is by this, never by date
    BuildDateKey    INT         NOT NULL,
    BuildLabel      VARCHAR(40) NOT NULL,
    -- A release candidate is the thing being shipped. Readiness is always
    -- computed against ONE specific build, never "the latest of everything".
    IsReleaseCandidate BIT      NOT NULL,
    CONSTRAINT FK_Build_Date FOREIGN KEY (BuildDateKey) REFERENCES dbo.Dim_Date(DateKey)
);
GO

CREATE TABLE dbo.Dim_Requirement (
    RequirementKey  INT IDENTITY(1,1) PRIMARY KEY,
    RequirementID   VARCHAR(12) NOT NULL UNIQUE,     -- e.g. REQ-0142
    Title           VARCHAR(160) NOT NULL,
    ReqType         VARCHAR(16) NOT NULL
        CHECK (ReqType IN ('Functional','Performance','Safety','Interface','Regulatory')),
    -- The ship gate is computed over MustShip only. A readiness percentage
    -- that mixes must-ship and nice-to-have is arithmetic without a decision
    -- attached: it cannot tell you whether to ship.
    Priority        VARCHAR(12) NOT NULL
        CHECK (Priority IN ('MustShip','ShouldShip','Nice')),
    SubsystemKey    INT         NOT NULL,
    OwnerKey        INT         NOT NULL,
    BaselinedDateKey INT        NOT NULL,
    -- Requirements can be withdrawn. A withdrawn requirement is not a failure
    -- to verify, and counting it as one understates readiness.
    ReqStatus       VARCHAR(12) NOT NULL
        CHECK (ReqStatus IN ('Baselined','Withdrawn')),
    CONSTRAINT FK_Req_Subsystem FOREIGN KEY (SubsystemKey)    REFERENCES dbo.Dim_Subsystem(SubsystemKey),
    CONSTRAINT FK_Req_Owner     FOREIGN KEY (OwnerKey)        REFERENCES dbo.Dim_Person(PersonKey),
    CONSTRAINT FK_Req_Date      FOREIGN KEY (BaselinedDateKey) REFERENCES dbo.Dim_Date(DateKey)
);
GO

CREATE TABLE dbo.Dim_TestCase (
    TestCaseKey    INT IDENTITY(1,1) PRIMARY KEY,
    TestCaseID     VARCHAR(12) NOT NULL UNIQUE,      -- e.g. TC-0318
    RequirementKey INT         NOT NULL,
    -- Test level is the evidence grade. Ref_VerificationPolicy decides which
    -- grade is sufficient for which requirement type; this column only records
    -- what the test actually is.
    TestLevel      VARCHAR(16) NOT NULL
        CHECK (TestLevel IN ('Unit','Integration','HIL','Field')),
    AutomationLevel VARCHAR(12) NOT NULL
        CHECK (AutomationLevel IN ('Automated','Manual')),
    ExpectedDurationMin INT    NOT NULL,
    CONSTRAINT FK_TC_Req FOREIGN KEY (RequirementKey) REFERENCES dbo.Dim_Requirement(RequirementKey)
);
GO

-- =============================================================================
