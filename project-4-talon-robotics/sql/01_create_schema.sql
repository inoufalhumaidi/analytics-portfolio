/*
================================================================================
Project 4 — Talon Robotics: Payload Deployment Delivery
Script:  01_create_schema.sql
Purpose: Create the TalonDelivery database and its dimensional model.

BUSINESS QUESTION
    Is the new payload ready to ship, and what is still open?

THE SCHEMA DECISION THAT MAKES THE ANSWER POSSIBLE

    A verification is a DATED FACT AGAINST A BUILD, not an attribute of a
    requirement.

    The obvious model puts a Verified flag, or a VerifiedDate, on the
    requirement row. It is simpler, it is what most trackers actually do, and
    it makes the central question of this project impossible to ask. A test
    result is evidence about ONE BUILD. If REQ-0142 passed on build 12 and the
    flight-control subsystem changed in build 17, the flag still says Verified
    and is describing software that no longer exists.

    So Fact_TestRun carries both a TestCaseKey and a BuildKey, and
    Fact_BuildSubsystemChange records which subsystems each build touched.
    Staleness is then COMPUTABLE rather than asserted: a verification is
    current if nothing it depended on has moved since it ran.

    This is the same shape as Project 3's price agreements. A contracted price
    is true between two dates; a test result is true for one build. Storing
    either as an attribute lets today's answer silently govern yesterday's
    question.

TWO MORE DECISIONS WORTH THE COMMENT

    Requirements change, and the change is recorded. Fact_RequirementChange
    exists because a requirement that was reworded after it was verified is
    just as stale as one whose code moved -- the test may now be checking the
    wrong thing. Without this table, "verified" silently means "verified
    against some earlier version of the sentence".

    What COUNTS as verification is a reference table, not a CASE expression.
    Ref_VerificationPolicy states, per requirement type, which test level is
    sufficient evidence -- a safety requirement is not verified by a unit test.
    It is the single most contestable input in the analysis, so it lives where
    a systems engineer can see it, challenge it and change it, exactly as the
    erosion benchmark does in Project 3.

DATA DISCLOSURE
    Talon Robotics is a fictional mechatronics company. All data is synthetic
    and generated by 02_generate_synthetic_data.sql. No confidential data is
    used and no claim is made about any production system.
================================================================================
*/

